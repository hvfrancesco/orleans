//! G-code serialisation.
//!
//! Targets the GRBL dialect by default, with a small Marlin dialect variant.
//! The output is deliberately boring: absolute millimetres, no arcs, one `G1`
//! per segment.

use std::fmt::Write as _;

use orleans_core::{Job, Op};

/// Controller dialect for the few commands that differ between GRBL and
/// Marlin. The motion and laser words are shared.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum GcodeDialect {
    #[default]
    Grbl,
    Marlin,
}

/// How the controller should interpret `S`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LaserMode {
    /// `M3`: constant power while moving.
    M3,
    /// `M4`: dynamic power, scaled by the actual velocity (GRBL laser mode).
    M4,
}

impl LaserMode {
    pub fn code(self) -> u8 {
        match self {
            LaserMode::M3 => 3,
            LaserMode::M4 => 4,
        }
    }
}

#[derive(Clone, Debug)]
pub struct GcodeOptions {
    pub laser_mode: LaserMode,
    /// `S` value that corresponds to 100 % power.
    pub max_s: u32,
    /// Decimal places for coordinates.
    pub decimals: usize,
    /// Emit a comment when the active layer changes.
    pub comment_layers: bool,
    /// Controller-specific preamble and workspace commands.
    pub dialect: GcodeDialect,
}

impl Default for GcodeOptions {
    fn default() -> Self {
        Self {
            laser_mode: LaserMode::M3,
            max_s: 1000,
            decimals: 3,
            comment_layers: true,
            dialect: GcodeDialect::Grbl,
        }
    }
}

impl GcodeOptions {
    /// Map a 0..=100 percentage to the machine's `S` range.
    pub fn power_to_s(&self, power: f64) -> u32 {
        let pct = power.clamp(0.0, 100.0) / 100.0;
        (pct * f64::from(self.max_s)).round() as u32
    }
}

/// Render a planned job to G-code.
pub fn write(job: &Job, opt: &GcodeOptions) -> String {
    let mut out = String::new();
    let _ = write_to(job, opt, &mut out);
    out
}

pub fn write_to(job: &Job, opt: &GcodeOptions, out: &mut String) -> std::fmt::Result {
    out.push_str("; generated by orleans\n");
    out.push_str("; units: mm, absolute positioning\n");
    match opt.dialect {
        GcodeDialect::Grbl => out.push_str("G21\nG90\nG17\nG54\nM5\n"),
        // Marlin supports G21/G90 and the laser words, but workspace and
        // plane-select commands vary across builds. Keep the preamble to the
        // portable subset.
        GcodeDialect::Marlin => out.push_str("G21\nG90\nM5\n"),
    }

    let mut active_layer: Option<usize> = None;

    for op in &job.ops {
        match op {
            Op::Rapid { to } => {
                out.push_str("G0 X");
                out.push_str(&num(to.x, opt.decimals));
                out.push_str(" Y");
                out.push_str(&num(to.y, opt.decimals));
                out.push('\n');
            }
            Op::Cut {
                polyline,
                params,
                layer,
            } => {
                if opt.comment_layers && active_layer != Some(*layer) {
                    let _ = writeln!(out, "; layer {layer}");
                    active_layer = Some(*layer);
                }
                let _ = writeln!(
                    out,
                    "M{} S{}",
                    opt.laser_mode.code(),
                    opt.power_to_s(params.power)
                );
                // The first point of a cut is where the head already is after
                // the preceding rapid, so only the following points are moved to.
                // `F` is modal in GRBL: emit it once per cut.
                for (i, point) in polyline.iter().skip(1).enumerate() {
                    out.push_str("G1 X");
                    out.push_str(&num(point.x, opt.decimals));
                    out.push_str(" Y");
                    out.push_str(&num(point.y, opt.decimals));
                    if i == 0 {
                        out.push_str(" F");
                        let _ = write!(out, "{:.0}", params.speed.max(1.0));
                    }
                    out.push('\n');
                }
                out.push_str("M5\n");
            }
        }
    }

    out.push_str("M5\nG0 X0");
    out.push_str(" Y0\n");
    Ok(())
}

fn num(v: f64, decimals: usize) -> String {
    let mut s = format!("{v:.decimals$}");
    if s.contains('.') {
        while s.ends_with('0') {
            s.pop();
        }
        if s.ends_with('.') {
            s.pop();
        }
    }
    if s == "-0" {
        s = "0".to_owned();
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use kurbo::Point;
    use orleans_core::{CutParams, Job, JobStats, Op};

    fn job() -> Job {
        Job {
            ops: vec![
                Op::Rapid {
                    to: Point::new(1.0, 2.0),
                },
                Op::Cut {
                    polyline: vec![
                        Point::new(1.0, 2.0),
                        Point::new(3.0, 2.0),
                        Point::new(3.0, 4.5),
                    ],
                    params: CutParams::new(1200.0, 50.0, 1),
                    layer: 0,
                },
            ],
            stats: JobStats::default(),
        }
    }

    #[test]
    fn emits_preamble_and_epilogue() {
        let g = write(&job(), &GcodeOptions::default());
        assert!(g.starts_with("; generated by orleans"));
        assert!(g.contains("G21\nG90\nG17\nG54\nM5\n"));
        assert!(g.trim_end().ends_with("M5\nG0 X0 Y0"));
    }

    #[test]
    fn marlin_preamble_omits_workspace_and_plane_words() {
        let opt = GcodeOptions {
            dialect: GcodeDialect::Marlin,
            max_s: 255,
            ..Default::default()
        };
        let g = write(&job(), &opt);
        assert!(g.starts_with("; generated by orleans"));
        assert!(g.contains("G21\nG90\nM5\n"));
        assert!(!g.contains("G17"));
        assert!(!g.contains("G54"));
        assert!(g.contains("M3 S128\n"));
    }

    #[test]
    fn maps_power_percentage_to_s() {
        let opt = GcodeOptions {
            max_s: 1000,
            ..Default::default()
        };
        assert_eq!(opt.power_to_s(50.0), 500);
        assert_eq!(opt.power_to_s(150.0), 1000);
        assert_eq!(opt.power_to_s(-1.0), 0);
    }

    #[test]
    fn emits_cut_moves_with_feed() {
        let g = write(&job(), &GcodeOptions::default());
        assert!(g.contains("G0 X1 Y2\n"));
        assert!(g.contains("M3 S500\n"));
        assert!(g.contains("G1 X3 Y2 F1200\n"));
        assert!(g.contains("G1 X3 Y4.5\n"));
        assert_eq!(g.matches("F1200").count(), 1);
        // Two cut points after the start.
        assert_eq!(g.matches("G1 X").count(), 2);
    }

    #[test]
    fn trims_trailing_zeroes() {
        assert_eq!(num(1.500, 3), "1.5");
        assert_eq!(num(2.0, 3), "2");
        assert_eq!(num(-0.0001, 3), "0");
    }
}
